-- all columns and the first 10 records from the supply_chain table.
select * from  supply_chain_data LIMIT 10;

--  total number of records in your supply chain dataset.
select count(*) from supply_chain_data;


--  all unique product types in your supply_chain_data table.
SELECT DISTINCT `Product type`
FROM supply_chain_data;

--  all products where the Price is greater than 10.
SELECT *
FROM supply_chain_data
WHERE Price > 10;

--  all records sorted by Price from highest to lowest.
select * from supply_chain_data 
order by price desc;

--  average price of all products in your supply_chain_data table.
SELECT AVG(Price) AS avg_price
FROM supply_chain_data;

--  total revenue generated by all products in your supply_chain_data table.
SELECT SUM(`Revenue generated`) AS total_revenue
FROM supply_chain_data;

--  total number of products sold using the Number of products sold column.
SELECT SUM(`Number of products sold`) AS total_products_sold
FROM supply_chain_data;

--  the total revenue generated by each product type.
SELECT `Product type`,
       SUM(`Revenue generated`) AS total_revenue
FROM supply_chain_data
GROUP BY `Product type`;

--  product types whose average price is greater than 10.
select 'product type' , avg(price) as Avg_price 
from supply_chain_data
group by ' product type '
having avg_price > 40 ;

--  the number of records in each product type, showing only product types that have more than 10 records.
SELECT `Product type`,
       COUNT(*) AS total_records
FROM supply_chain_data
GROUP BY `Product type`
HAVING COUNT(*) > 10;

--  the product with the highest price in your supply chain dataset.
SELECT *
FROM supply_chain_data
ORDER BY Price DESC
LIMIT 1;

--  the top 5 products with the highest revenue generated.
SELECT *
FROM supply_chain_data
ORDER BY `Revenue generated` DESC
LIMIT 5;

--  the total revenue generated by each SKU, displaying the SKU and its total revenue.
SELECT SKU,
       SUM(`Revenue generated`) AS total_revenue
FROM supply_chain_data
GROUP BY SKU;

--  average manufacturing cost for each product type, 
-- showing only product types with an average manufacturing cost greater than 40.
SELECT `Product type`,
       AVG(`Manufacturing costs`) AS avg_manufacturing_cost
FROM supply_chain_data
GROUP BY `Product type`
HAVING AVG(`Manufacturing costs`) > 40;

 -- total number of products sold for each product type, sorted from highest to lowest total sales
SELECT `Product type`,
       SUM(`Number of products sold`) AS total_products_sold
FROM supply_chain_data
GROUP BY `Product type`
ORDER BY total_products_sold DESC;

-- products whose stock level is below 50, displaying the SKU and stock level.
SELECT SKU, `Stock levels`
FROM supply_chain_data
WHERE `Stock levels` < 50;


-- total shipping cost for each shipping carrier, sorted from highest to lowest.
SELECT `Shipping carriers`,
       SUM(`Shipping costs`) AS total_shipping_cost
FROM supply_chain_data
GROUP BY `Shipping carriers`
ORDER BY total_shipping_cost DESC;


-- number of products for each inspection result, showing only inspection results with more than 10 records.
SELECT `Inspection results`,
       COUNT(*) AS total_products
FROM supply_chain_data
GROUP BY `Inspection results`
HAVING COUNT(*) > 10;


-- the top 5 SKUs with the highest defect rates, sorted from highest to lowest.
SELECT SKU,
       `Defect rates`
FROM supply_chain_data
ORDER BY `Defect rates` DESC
LIMIT 5;


